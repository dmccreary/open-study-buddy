#!/usr/bin/env python3
"""Write edition.py: the few constants the Pico needs from agent.toml (Chapter 16).

    python3 make_edition.py            # writes ../edition.py

The Pico never reads TOML, JSON calendars, or ICS feeds. It gets this one small
Python file of constants, made on the computer from the same agent.toml the
server uses, so the device and the server cannot disagree about the school's id
or the mascot file.
"""
import argparse
import os
import sys

import agent_config
import topics

HERE = os.path.dirname(os.path.abspath(__file__))


def rgb565(hexcolor):
    r, g, b = (int(hexcolor[i:i + 2], 16) for i in (1, 3, 5))
    return (r & 0xF8) << 8 | (g & 0xFC) << 3 | b >> 3


def render(cfg, room, device):
    s, m = cfg["school"], cfg["mascot"]
    lines = [
        "# edition.py -- GENERATED by server/make_edition.py from agent.toml. Do not edit by hand.",
        "",
        "SCHOOL_NAME = %r" % s["name"],
        "SCHOOL_SHORT = %r" % (s.get("short_name") or s["name"]),
        "SLOGAN = %r" % s.get("slogan", ""),
        "SCHOOL_ID = %r" % s["id"],
        "ROOM = %r" % topics.slug(room),
        "DEVICE_ID = %r" % device,
        "PRIMARY = 0x%04X          # %s as RGB565" % (rgb565(s["primary_color"]), s["primary_color"]),
        "ACCENT = 0x%04X           # %s as RGB565" % (rgb565(s["accent_color"]), s["accent_color"]),
        "MASCOT_NAME = %r" % m["name"],
        "MASCOT_FILE = %r" % m["file"],
        "MASCOT_SIZE = %d" % m["size"],
        "WAKE_PHRASE = %r" % cfg["wake"]["phrase"],
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--config", default=os.path.join(HERE, "agent.toml"))
    p.add_argument("--room", default="214", help="this device's classroom")
    p.add_argument("--device", default="desk-07", help="this device's id")
    p.add_argument("--out", default=os.path.join(os.path.dirname(HERE), "edition.py"))
    args = p.parse_args(argv)
    cfg = agent_config.load(args.config)
    errors, _ = agent_config.check(cfg)
    if errors:
        sys.exit("Fix agent.toml first:\n  " + "\n  ".join(errors))
    text = render(cfg, args.room, args.device)
    with open(args.out, "w") as f:
        f.write(text)
    print(text)
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
